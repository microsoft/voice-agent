// Interact with the isolated offline cockpit first, then run with agent-browser eval --stdin.
(async () => {
  const { browserOwner, command, phoneSnapshot } = await import("/static/cockpit.js");
  const { autopilot } = await import("/static/autopilot-sim.mjs");
  const { MODEL_UNITS_PER_M, MARKER_PERIOD } = await import("/static/road-scene.mjs");
  const $ = (id) => document.getElementById(id);
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const waitFor = async (predicate) => {
    for (let i = 0; i < 150; i++) {
      if (predicate()) return;
      await new Promise((resolve) => setTimeout(resolve, 20));
    }
    throw new Error("Browser condition timed out.");
  };
  const execute = async (name, args, ok = true) => {
    const packet = await command(name, args);
    document.dispatchEvent(new CustomEvent("cockpit-snapshot", { detail: packet.state }));
    assert(packet.result.ok === ok, `${name}: ${JSON.stringify(packet.result)}`);
    return packet.result;
  };
  assert(navigator.userActivation.hasBeenActive, "Interact with the page before testing real local audio playback.");
  await waitFor(() => $("control-status").textContent === "Controls connected");
  await waitFor(() => $("car-view").dataset.modelReady === "true");
  const scene = $("car-view").dataset;
  assert(Number(scene.trafficCount) >= 4 && Number(scene.trafficCount) <= 5, "Sparse bounded 3D traffic");
  assert(scene.trafficKinds === "car,bicycle,pedestrian", "Cars and non-motor traffic are in the real scene");
  const originalOwner = browserOwner();
  assert(autopilot.state.running && autopilot.state.mode === "disengaged", "EPA starts automatically without assistance");
  await waitFor(() => Number(scene.speedKmh) > 0 && Number(scene.distanceM) > 0);
  assert(scene.motionSource === "reference", "EPA is the default driving source");
  const automaticDistance = Number(scene.distanceM);
  await new Promise((resolve) => setTimeout(resolve, 200));
  assert(Number(scene.distanceM) > automaticDistance, "Default playback advances without start/resume commands");
  assert(document.documentElement.scrollWidth <= innerWidth, "No horizontal overflow");
  for (const id of ["sim-title", "navigation-title", "cluster-title", "climate-title", "media-title", "phone-title"]) assert($(id), id);
  await execute("set_vehicle_doors", { door: "all", is_open: false });
  await execute("set_vehicle_windows", { window: "all", is_open: false });
  for (const lid of ["hood", "trunk"]) await execute("set_vehicle_lid", { lid, is_open: false });
  await execute("control_autopilot", { action: "resume" }, false);
  await execute("control_autopilot", { action: "engage", target_speed_kmh: 42, following_gap: 4, lane_keeping: true });
  await waitFor(() => scene.motionSource === "simulator");
  assert($("sim-state").textContent.includes("active"), "Visible engagement");
  const distanceBefore = Number(scene.roadDistanceM);
  await new Promise((resolve) => setTimeout(resolve, 450));
  if (matchMedia("(prefers-reduced-motion: reduce)").matches) {
    assert(Number(scene.roadDistanceM) === distanceBefore && scene.wheelsRolling === "false", "Reduced motion freezes the real road and wheels");
  } else {
    assert(Number(scene.roadDistanceM) > distanceBefore && scene.wheelsRolling === "true", "Actual model and road move together");
    const expected = Number(scene.distanceM) * MODEL_UNITS_PER_M % MARKER_PERIOD;
    assert(Math.abs(Number(scene.roadPhase) - expected) < .001, "Road uses exactly the selected wheel distance");
    assert(scene.roadDistanceM === scene.distanceM, "Road has no second clock or simulator advancement");
  }
  $("sim-speed").value = 47;
  $("sim-speed").dispatchEvent(new Event("input"));
  assert($("sim-target-value").textContent === "47 km/h", "Target slider previews its value");
  $("sim-speed").dispatchEvent(new Event("change"));
  await waitFor(() => autopilot.state.target_speed_kmh === 47);
  $("sim-gap").value = 5;
  $("sim-gap").dispatchEvent(new Event("change"));
  await waitFor(() => autopilot.state.following_gap === 5);
  $("sim-lane").checked = false;
  $("sim-lane").dispatchEvent(new Event("change"));
  await waitFor(() => !autopilot.state.lane_keeping);
  await execute("set_vehicle_windows", { window: "front_left", is_open: true });
  await waitFor(() => Number(scene.window_front_left) < -1);
  assert(autopilot.state.mode === "active" && autopilot.state.running, "Opening a window does not disengage assistance or stop playback");
  await execute("set_vehicle_windows", { window: "front_left", is_open: false });
  $("sim-scenario").value = "lane_loss";
  $("sim-scenario").dispatchEvent(new Event("change"));
  await waitFor(() => autopilot.state.mode === "takeover_required");
  assert(autopilot.state.running, "Takeover keeps background driving active");
  await new Promise((resolve) => setTimeout(resolve, 80));
  const fallbackDistance = Number(scene.distanceM);
  await new Promise((resolve) => setTimeout(resolve, 150));
  assert(Number(scene.distanceM) > fallbackDistance && scene.motionSource === "reference", "Takeover returns to EPA without stopping playback");
  assert($("sim-acknowledge").checkVisibility(), "Takeover acknowledgement is visible outside settings");
  await execute("control_autopilot", { action: "engage" }, false);
  $("sim-scenario").value = "clear";
  $("sim-scenario").dispatchEvent(new Event("change"));
  await waitFor(() => !$("sim-acknowledge").disabled);
  $("sim-acknowledge").click();
  assert(autopilot.state.mode === "disengaged", "Manual acknowledgement does not re-engage");
  await execute("control_autopilot", { action: "engage" });
  Object.defineProperty(document, "hidden", { configurable: true, value: true });
  document.dispatchEvent(new Event("visibilitychange"));
  assert(autopilot.state.running && autopilot.state.mode === "disengaged", "Hidden page disengages assistance without stopping EPA");
  delete document.hidden;
  document.dispatchEvent(new Event("visibilitychange"));
  assert(autopilot.state.running && autopilot.state.mode === "disengaged", "Visible page never silently re-engages assistance");
  await waitFor(() => scene.motionSource === "reference");
  if (!matchMedia("(prefers-reduced-motion: reduce)").matches) assert(scene.roadDistanceM === scene.distanceM, "Reference trace drives the same 3D road and wheels");
  await execute("control_autopilot", { action: "engage" });
  await execute("set_vehicle_doors", { door: "front_left", is_open: true });
  await execute("set_vehicle_windows", { window: "front_left", is_open: true });
  await execute("set_vehicle_lid", { lid: "hood", is_open: true });
  await waitFor(() => Math.abs(Number(scene.front_left)) > 1 && Number(scene.window_front_left) < -1 && Math.abs(Number(scene.hood)) > .5);
  assert(autopilot.state.running && autopilot.state.mode === "disengaged", "Doors and compartments disengage assistance but keep EPA playing");
  await execute("set_vehicle_doors", { door: "front_left", is_open: false });
  await execute("set_vehicle_windows", { window: "front_left", is_open: false });
  await execute("set_vehicle_lid", { lid: "hood", is_open: false });
  await execute("set_climate", { temperature_c: 23, fan: 4, defrost: true });
  assert($("temperature").textContent === "23" && $("climate-defrost").checked, "Climate authoritative render");
  await execute("set_destination", { destination: "Public Library" });
  assert($("destination").textContent === "Public Library", "Saved destination");
  await execute("set_cluster_preferences", { units: "imperial", theme: "light", layout: "compact", brightness: 70 });
  assert(document.documentElement.dataset.cockpitTheme === "light", "Cluster theme");
  await waitFor(() => $("cluster-speed").textContent.includes("mph"));
  assert(Number($("cluster-readout").style.opacity) === .7, "Merged speed readout keeps instrument brightness");
  await execute("set_phone_preferences", { notifications: false, detail: "detailed" });
  assert($("phone-preference-status").textContent.includes("disabled"), "Phone-panel preferences are visible");
  const audio = $("local-audio");
  const buffer = new ArrayBuffer(44 + 16000);
  const view = new DataView(buffer);
  const text = (at, value) => [...value].forEach((c, i) => view.setUint8(at + i, c.charCodeAt(0)));
  text(0, "RIFF"); view.setUint32(4, buffer.byteLength - 8, true); text(8, "WAVE"); text(12, "fmt ");
  view.setUint32(16, 16, true); view.setUint16(20, 1, true); view.setUint16(22, 1, true);
  view.setUint32(24, 8000, true); view.setUint32(28, 16000, true);
  view.setUint16(32, 2, true); view.setUint16(34, 16, true); text(36, "data"); view.setUint32(40, 16000, true);
  const transfer = new DataTransfer();
  transfer.items.add(new File([buffer], "browser-only-test.wav", { type: "audio/wav" }));
  $("media-file").files = transfer.files;
  $("media-file").dispatchEvent(new Event("change"));
  await waitFor(() => audio.readyState >= 1);
  await execute("control_media", { action: "mute" });
  await execute("control_media", { action: "play" });
  assert(!audio.paused, "Real browser-local audio playback");
  await execute("control_media", { action: "pause" });
  assert(audio.paused, "Playback pause confirmed");
  await execute("control_media", { action: "seek", position_seconds: .2 });
  await execute("set_media_volume", { volume_percent: 35 });
  assert(audio.volume === .35, "Media volume controls actual file audio");
  assert(!document.querySelector('[data-step="searching"]').checkVisibility(), "Routine pipeline hides discovery");
  assert($("sources").children.length === 0, "No WebIQ calls for local controls");
  await execute("control_autopilot", { action: "engage" });
  await execute("control_phone", { action: "dial", contact: "Alex Chen" });
  await waitFor(() => phoneSnapshot().call_state === "active");
  const originalSend = WebSocket.prototype.send;
  try {
    WebSocket.prototype.send = function (data) {
      if (typeof data === "string" && ["ping", "browser_state"].includes(JSON.parse(data).type)) return;
      return originalSend.call(this, data);
    };
    await new Promise((resolve) => setTimeout(resolve, 6500));
    assert(autopilot.state.running && autopilot.state.mode === "disengaged", "Connection loss disengages assistance, not EPA");
    await waitFor(() => $("control-status").textContent.includes("disconnected"));
    assert(!browserOwner() && !$("reconnect-controls").hidden, "Control loss offers an inline reconnect instead of a stale owner");
    assert(phoneSnapshot().call_state === "ended" && !phoneSnapshot().available
      && $("phone-state").textContent === "Controls disconnected", "Connection loss ends the local call and updates its visible state");
    assert($("header-connection").textContent === "CONTROLS OFFLINE", "Merged header lamp follows real control loss");
    assert($("connect").disabled, "Voice connection is unavailable without cockpit controls");
  } finally { WebSocket.prototype.send = originalSend; }
  $("reconnect-controls").click();
  await waitFor(() => $("control-status").textContent === "Controls connected");
  assert(browserOwner() !== originalOwner && $("reconnect-controls").hidden, "Reconnect establishes a new owner and clears its recovery action");
  assert($("header-connection").textContent === "CONTROLS READY", "Merged header lamp follows control recovery");
  assert(autopilot.state.running && autopilot.state.mode === "disengaged", "Reconnect preserves EPA without engaging assistance");
  assert(phoneSnapshot().available && phoneSnapshot().call_state === "ended", "Reconnect restores phone controls without resuming a call");
  document.querySelector(".phone-address-book").open = false;
  return "PASS: unified 3D road and wheels, bounded traffic, body animations, six control domains, takeover/visibility/reconnection, source arbitration, reduced motion, real local audio, zero discovery or web lookups";
})();

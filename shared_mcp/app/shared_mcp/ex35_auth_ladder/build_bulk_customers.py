"""Write bulk_customers.json: the 20K-name directory as extra Example 35 customers.

Source: the loan-officer directory the phonetic name search was benchmarked on
(docs/voice_agent/project3_umw/v1/data/officers_20k.json). Every name becomes a
fictional customer with a date of birth, state and masked phone derived from a
hash of its id, so the file is reproducible. Names already in otp_candidates.json
are skipped: one name, one customer.

    python3 build_bulk_customers.py <officers_20k.json> <otp_candidates.json> bulk_customers.json
"""
import hashlib
import json
import sys
from pathlib import Path

officers = json.loads(Path(sys.argv[1]).read_text())["officers"]
curated = json.loads(Path(sys.argv[2]).read_text())["candidates"]
out = Path(sys.argv[3])

taken = {c["full_name"].strip().lower() for c in curated}
AREA_CODES = ("206", "212", "303", "312", "404", "415", "425", "503", "512", "602", "617", "702", "713", "801", "919")

rows = []
skipped = []
for officer in officers:
    name = officer["full_name"].strip()
    if name.lower() in taken:
        skipped.append(name)
        continue
    taken.add(name.lower())
    number = officer["officer_id"].split("-")[-1]
    seed = int(hashlib.sha256(officer["officer_id"].encode()).hexdigest(), 16)
    year, month, day = 1950 + seed % 51, 1 + (seed >> 8) % 12, 1 + (seed >> 16) % 28
    branch = officer.get("branch") or ""
    state = branch.rsplit(",", 1)[-1].strip() if "," in branch else "WA"
    phone = f"+1 ({AREA_CODES[(seed >> 24) % len(AREA_CODES)]}) ***-{(seed >> 32) % 10000:04d}"
    rows.append([f"cust-{number}", name, f"{year:04d}-{month:02d}-{day:02d}", state, phone, officer.get("aliases") or []])

document = {
    "fixture": "fictional",
    "notice": (
        "Generated by build_bulk_customers.py from the 20K loan-officer name directory. Names are "
        "fictional; dates of birth, states and phones are derived from a hash of the id. Names in "
        "otp_candidates.json are skipped."
    ),
    "fields": ["candidate_id", "full_name", "date_of_birth", "state", "phone_masked", "aliases"],
    "rows": rows,
}
out.write_text(json.dumps(document, ensure_ascii=False, separators=(",", ":")) + "\n")
print("customers:", len(rows), "| skipped (already curated):", len(skipped), skipped)
